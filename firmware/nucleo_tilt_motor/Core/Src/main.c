/* Drive the motor driver: enable = STBY, duty = PWM compare (0..65535). */
static void motor_set(uint8_t enable, uint32_t duty)
{
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, GPIO_PIN_SET);    // AIN1
  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_6, GPIO_PIN_RESET);  // AIN2
  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, duty);
  HAL_GPIO_WritePin(GPIOC, GPIO_PIN_7, enable ? GPIO_PIN_SET : GPIO_PIN_RESET); // STBY
}
